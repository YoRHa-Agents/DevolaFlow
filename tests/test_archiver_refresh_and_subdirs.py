def test_stale_copy_without_refresh_left_untouched(archiver, tmp_path: Path, capsys) -> None:
    """A drifted destination copy is reported STALE, never overwritten by default."""
    research = _research(tmp_path)
    (research / "v9.9.0_retrospective.md").write_text("NEW", encoding="utf-8")
    dest = _dest(tmp_path, "v9.9.0")
    dest.mkdir(parents=True)
    (dest / "v9.9.0_retrospective.md").write_text("OLD", encoding="utf-8")

    assert archiver.archive("9.9.0") == 0

    assert (dest / "v9.9.0_retrospective.md").read_text(encoding="utf-8") == "OLD"
    out = capsys.readouterr().out
    assert "STALE" in out
    assert "--refresh" in out
    assert "REFRESH " not in out


def test_refresh_overwrites_stale_copy(archiver, tmp_path: Path, capsys) -> None:
    """--refresh overwrites a drifted destination copy (status REFRESH)."""
    research = _research(tmp_path)
    (research / "v9.9.0_retrospective.md").write_text("NEW", encoding="utf-8")
    dest = _dest(tmp_path, "v9.9.0")
    dest.mkdir(parents=True)
    (dest / "v9.9.0_retrospective.md").write_text("OLD", encoding="utf-8")

    assert archiver.archive("9.9.0", refresh=True) == 0

    assert (dest / "v9.9.0_retrospective.md").read_text(encoding="utf-8") == "NEW"
    assert "REFRESH" in capsys.readouterr().out

    # Idempotence: a second refresh run is a byte-level no-op (EXISTS).
    assert archiver.archive("9.9.0", refresh=True) == 0
    out = capsys.readouterr().out
    assert "REFRESH " not in out
    assert "EXISTS" in out


def test_refresh_regenerates_readme_index(archiver, tmp_path: Path) -> None:
    """The README index is regenerated under --refresh when sources changed."""
    research = _research(tmp_path)
    (research / "v9.9.0_retrospective.md").write_text("R", encoding="utf-8")
    assert archiver.archive("9.9.0") == 0
    readme_path = _dest(tmp_path, "v9.9.0") / "README.md"
    assert "gap_analysis" not in readme_path.read_text(encoding="utf-8")

    (research / "v9.9.0_gap_analysis.md").write_text("GA", encoding="utf-8")

    # Default path: README untouched (legacy exists-means-skip semantics).
    assert archiver.archive("9.9.0") == 0
    assert "v9.9.0_gap_analysis.md" not in readme_path.read_text(encoding="utf-8")

    # Refresh path: index regenerated to match the changed source set.
    assert archiver.archive("9.9.0", refresh=True) == 0
    assert "* `v9.9.0_gap_analysis.md`" in readme_path.read_text(encoding="utf-8")


def test_misc_archives_only_nonversioned_root_files(archiver, tmp_path: Path) -> None:
    """--misc gathers cycle-less root files; dirs + cycle-versioned files excluded.

    Cycle-LESS ``v``-prefixed names (``v10_internal_...`` — no
    ``v<MAJOR>.<MINOR>.`` component) route to misc/ because no cycle
    prefix can ever gather them; dot-form (``v9.9.0_...``) and dash-form
    (``v15-cycle_...``) versioned names stay out of misc.
    """
    research = _research(tmp_path)
    (research / "survey.md").write_text("S", encoding="utf-8")
    (research / "notes_analysis.md").write_text("N", encoding="utf-8")
    (research / "v10_internal_directions.md").write_text("I", encoding="utf-8")
    (research / "v9.9.0_gap_analysis.md").write_text("V", encoding="utf-8")
    (research / "v15-cycle_design_review.md").write_text("C", encoding="utf-8")
    (research / "adr").mkdir()
    (research / "adr" / "some-adr.md").write_text("A", encoding="utf-8")

    assert archiver.archive_misc() == 0

    dest = _dest(tmp_path, "misc")
    produced = sorted(str(p.relative_to(dest)) for p in dest.rglob("*") if p.is_file())
    assert produced == ["README.md", "notes_analysis.md", "survey.md", "v10_internal_directions.md"]
    readme = (dest / "README.md").read_text(encoding="utf-8")
    assert "* `notes_analysis.md`" in readme
    assert "* `survey.md`" in readme
    assert "* `v10_internal_directions.md`" in readme
    assert "v9.9.0_gap_analysis.md" not in readme
    assert "v15-cycle_design_review.md" not in readme


def test_misc_supports_dry_run_and_refresh(archiver, tmp_path: Path, capsys) -> None:
    """--misc honours --dry-run (zero writes) and --refresh (stale heal)."""
    research = _research(tmp_path)
    (research / "survey.md").write_text("NEW", encoding="utf-8")
    dest = _dest(tmp_path, "misc")

    assert archiver.archive_misc(dry_run=True) == 0
    assert not dest.exists()
    assert "WOULD" in capsys.readouterr().out

    dest.mkdir(parents=True)
    (dest / "survey.md").write_text("OLD", encoding="utf-8")
    assert archiver.archive_misc() == 0
    assert (dest / "survey.md").read_text(encoding="utf-8") == "OLD"
    assert "STALE" in capsys.readouterr().out

    assert archiver.archive_misc(refresh=True) == 0
    assert (dest / "survey.md").read_text(encoding="utf-8") == "NEW"
    assert "REFRESH" in capsys.readouterr().out


def test_cli_version_and_misc_mutually_exclusive(
    archiver, monkeypatch: pytest.MonkeyPatch, capsys
) -> None:
    """CLI: exactly one of <version> / --misc — both or neither error out."""
    for argv in (
        ["archive_research_artifacts.py", "9.9.0", "--misc"],
        ["archive_research_artifacts.py"],
    ):
        monkeypatch.setattr(sys, "argv", argv)
        with pytest.raises(SystemExit) as excinfo:
            archiver.main()
        assert excinfo.value.code not in (0, None)
        capsys.readouterr()  # swallow argparse usage output
