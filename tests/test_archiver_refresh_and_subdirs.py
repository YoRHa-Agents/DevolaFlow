"""clean_repo Phase B1 — regression suite for the archiver upgrade.

Covers the three new behaviours of ``scripts/archive_research_artifacts.py``
(subdirectory recursion, ``--refresh``, ``--misc``) plus the DEFAULT-path
byte-equivalence regression pin (spec:
``.local/tasks/clean_repo/02-phase-B-archive.md`` step 2 — the default
invocation must keep producing the exact pre-B1 archive tree, byte for
byte, for inputs the pre-B1 script fully handled).

Every test runs against a ``tmp_path`` sandbox — ``_find_root`` is
monkeypatched so the script never touches the real repository tree.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "archive_research_artifacts.py"


def _load_archiver():
    spec = importlib.util.spec_from_file_location("archive_research_artifacts_b1", _SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["archive_research_artifacts_b1"] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture()
def archiver(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """Script module wired to a tmp_path sandbox root."""
    mod = _load_archiver()
    monkeypatch.setattr(mod, "_find_root", lambda: tmp_path)
    (tmp_path / ".local" / "research").mkdir(parents=True)
    return mod


def _research(tmp_path: Path) -> Path:
    return tmp_path / ".local" / "research"


def _dest(tmp_path: Path, leaf: str) -> Path:
    return tmp_path / "docs" / "cycle-archive" / leaf


def test_subdir_recursion_preserves_structure(archiver, tmp_path: Path) -> None:
    """Subdirs and evaluator artifacts route without flattening or history loss."""
    research = _research(tmp_path)
    (research / "v9.9.0_patches" / "nested").mkdir(parents=True)
    (research / "v9.9.0_patches" / "p1.md").write_text("patch-1", encoding="utf-8")
    (research / "v9.9.0_patches" / "nested" / "p2.md").write_text("patch-2", encoding="utf-8")
    (research / "v9.9.0_gap_analysis.md").write_text("gap", encoding="utf-8")
    (research / "v9.9.0_harness_evaluation.json").write_text("{}", encoding="utf-8")
    (research / "v9.9.0_nines.json").write_text("{}", encoding="utf-8")

    assert archiver.archive("9.9.0") == 0

    dest = _dest(tmp_path, "v9.9.0")
    assert (dest / "v9.9.0_patches" / "p1.md").read_text(encoding="utf-8") == "patch-1"
    assert (dest / "v9.9.0_patches" / "nested" / "p2.md").read_text(encoding="utf-8") == "patch-2"
    assert (dest / "v9.9.0_gap_analysis.md").read_text(encoding="utf-8") == "gap"
    assert (dest / "harness" / "v9.9.0_harness_evaluation.json").is_file()
    # Legacy NineS artifacts keep their historical route for archive compatibility.
    assert (dest / "nines" / "v9.9.0_nines.json").is_file()
    # The README index lists the subdir (trailing slash), NOT its contents
    # flattened into the flat buckets.
    readme = (dest / "README.md").read_text(encoding="utf-8")
    assert "* `v9.9.0_patches/`" in readme
    assert "### harness" in readme
    assert "### nines" in readme
    assert not (dest / "other" / "p1.md").exists()


